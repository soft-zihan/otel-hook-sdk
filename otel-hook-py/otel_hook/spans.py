def create_span(
    tracer: Tracer,
    name: str,
    attributes: Optional[Dict[str, Any]] = None,
    parent: Optional[Span] = None,
) -> Span:
    """Create a span with optional attributes.
    
    Args:
        tracer: OpenTelemetry Tracer 实例
        name: Span 名称
        attributes: 可选属性字典
        parent: 可选父 Span
        
    Returns:
        Span: 创建的 Span 实例
    """
    context = trace.set_span_in_context(parent) if parent else None
    span = tracer.start_span(name=name, context=context, attributes=attributes)
    return span


@contextmanager
def span_context(
    tracer: Tracer,
    name: str,
    attributes: Optional[Dict[str, Any]] = None,
):
    """Context manager for span with automatic error handling.
    
    Args:
        tracer: OpenTelemetry Tracer 实例
        name: Span 名称
        attributes: 可选属性字典
        
    Yields:
        Span: 当前 Span 实例
        
    Raises:
        Exception: 如果发生异常，会设置 ERROR 状态并重新抛出
    """
    with tracer.start_as_current_span(name=name, attributes=attributes) as span:
        try:
            yield span
            span.set_status(StatusCode.OK)
        except Exception as e:
            span.set_status(StatusCode.ERROR, str(e))
            span.set_attribute(SpanAttributes.ERROR_TYPE, type(e).__name__)
            span.set_attribute(SpanAttributes.ERROR_MESSAGE, str(e))
            raise


class SpanBuilder:
    """Builder pattern for creating spans with fluent API.
    
    Example:
        >>> builder = SpanBuilder(tracer, SpanNames.MODEL_CALL)
        >>> with builder.set_model("gpt-4").set_session("session_123") as span:
        ...     # 执行 LLM 调用
        ...     pass
    """

    def __init__(self, tracer: Tracer, name: str) -> None:
        self.tracer = tracer
        self.name = name
        self.attributes: Dict[str, Any] = {}
        self._span: Optional[Span] = None
        self._token: Optional[Any] = None

    def set_session(self, session_id: str, user_id: Optional[str] = None) -> "SpanBuilder":
        """设置会话和用户 ID"""
        self.attributes[SpanAttributes.SESSION_ID] = session_id
        if user_id:
            self.attributes[SpanAttributes.USER_ID] = user_id
        return self

    def set_agent(self, name: str, version: Optional[str] = None) -> "SpanBuilder":
        """设置智能体名称和版本"""
        self.attributes[SpanAttributes.AGENT_NAME] = name
        if version:
            self.attributes[SpanAttributes.AGENT_VERSION] = version
        return self

    def set_model(self, model: str) -> "SpanBuilder":
        """设置 LLM 模型名称"""
        self.attributes[SpanAttributes.LLM_MODEL] = model
        return self

    def set_temperature(self, temperature: float) -> "SpanBuilder":
        """设置 LLM 温度参数"""
        self.attributes[SpanAttributes.LLM_TEMPERATURE] = temperature
        return self

    def set_max_tokens(self, max_tokens: int) -> "SpanBuilder":
        """设置 LLM 最大 token 数"""
        self.attributes[SpanAttributes.LLM_MAX_TOKENS] = max_tokens
        return self

    def set_tool(self, name: str, args: Optional[Dict[str, Any]] = None) -> "SpanBuilder":
        """设置工具名称和参数"""
        self.attributes[SpanAttributes.TOOL_NAME] = name
        if args:
            self.attributes[SpanAttributes.TOOL_ARGS] = str(args)
        return self

    def start(self) -> Span:
        """启动 Span"""
        self._span = self.tracer.start_span(name=self.name, attributes=self.attributes)
        return self._span

    def start_as_current(self) -> Span:
        """启动 Span 并设置为当前 Span（用于上下文传播）"""
        from opentelemetry import context
        self._span = self.tracer.start_span(name=self.name, attributes=self.attributes)
        self._token = context.attach(trace.set_span_in_context(self._span))
        return self._span

    def end(self) -> None:
        """结束 Span"""
        if self._span:
            self._span.end()

    def __enter__(self) -> Span:
        return self.start_as_current()

    def __exit__(self, exc_type: Optional[type], exc_val: Optional[Exception], exc_tb: Optional[Any]) -> None:
        from opentelemetry import context
        if exc_type and self._span:
            self._span.set_status(StatusCode.ERROR, str(exc_val))
            self._span.set_attribute(SpanAttributes.ERROR_TYPE, exc_type.__name__)
        elif self._span:
            self._span.set_status(StatusCode.OK)
        self.end()
        if hasattr(self, '_token') and self._token:
            context.detach(self._token)
