"""Span definitions for agent monitoring.

This module defines all span types used in the trace backend.
Each span has a name, attributes, and semantic meaning.

Span Hierarchy:
===============

AGENT_SESSION (root)
├── LLM
│   ├── PROMPT_BUILD
│   ├── MODEL_CALL
│   └── RESPONSE_PARSE
├── TOOL_CALL
│   ├── TOOL_INPUT
│   └── TOOL_OUTPUT
└── CHAIN (multi-step orchestration)
    ├── STEP_1
    ├── STEP_2
    └── ...
"""

from typing import Optional, Dict, Any
from contextlib import contextmanager
from opentelemetry import trace
from opentelemetry.trace import StatusCode, Tracer, Span


